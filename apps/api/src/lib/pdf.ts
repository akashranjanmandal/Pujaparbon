import PDFDocument from "pdfkit";

/** Brand palette for printed documents: powder blue, sunset peach, ink. */
export const PDF = { red: "#2E688C", gold: "#D2643E", ink: "#1C202E", muted: "#606678", rule: "#E6E1D8", tint: "#E8F3FA" };

export function newDoc(opts: { landscape?: boolean } = {}) {
  const doc = new PDFDocument({ size: "A4", margin: 40, layout: opts.landscape ? "landscape" : "portrait", bufferPages: true });
  const chunks: Buffer[] = [];
  doc.on("data", (c: Buffer) => chunks.push(c));
  const done = new Promise<Buffer>((r) => doc.on("end", () => r(Buffer.concat(chunks))));
  return { doc, done };
}

/** Letterhead: coloured top band, business name, document title. */
export function letterhead(doc: PDFKit.PDFDocument, business: { name: string; address?: string | null; gstin?: string | null }, title: string, subtitle?: string) {
  const w = doc.page.width;
  doc.rect(0, 0, w, 10).fill(PDF.red);
  doc.rect(0, 10, w, 3).fill(PDF.gold);
  doc.fillColor(PDF.red).font("Helvetica-Bold").fontSize(20).text(business.name.toUpperCase(), 40, 32);
  doc.fillColor(PDF.muted).font("Helvetica").fontSize(8.5);
  if (business.address) doc.text(business.address, 40, 56, { width: 300 });
  if (business.gstin) doc.text(`GSTIN ${business.gstin}`, 40, doc.y + 1);
  doc.fillColor(PDF.ink).font("Helvetica-Bold").fontSize(14).text(title, w - 290, 34, { width: 250, align: "right" });
  if (subtitle) doc.fillColor(PDF.muted).font("Helvetica").fontSize(9).text(subtitle, w - 290, 54, { width: 250, align: "right" });
  doc.moveTo(40, 92).lineTo(w - 40, 92).strokeColor(PDF.rule).lineWidth(1).stroke();
  doc.y = 104;
}

export interface Col { key: string; label: string; width: number; align?: "left" | "right" | "center" }

/** Simple paginating table. */
export function table(doc: PDFKit.PDFDocument, cols: Col[], rows: Record<string, string | number>[], startY = doc.y) {
  const x0 = 40;
  let y = startY;
  const header = () => {
    doc.rect(x0, y, cols.reduce((s, c) => s + c.width, 0), 20).fill(PDF.tint);
    let x = x0;
    doc.fillColor(PDF.red).font("Helvetica-Bold").fontSize(8);
    for (const c of cols) {
      doc.text(c.label, x + 4, y + 6, { width: c.width - 8, align: c.align ?? "left" });
      x += c.width;
    }
    y += 22;
  };
  header();
  doc.font("Helvetica").fontSize(8.5).fillColor(PDF.ink);
  for (const r of rows) {
    if (y > doc.page.height - 70) {
      doc.addPage();
      y = 40;
      header();
      doc.font("Helvetica").fontSize(8.5).fillColor(PDF.ink);
    }
    let x = x0;
    for (const c of cols) {
      doc.fillColor(PDF.ink).text(String(r[c.key] ?? ""), x + 4, y + 3, { width: c.width - 8, align: c.align ?? "left", height: 12, ellipsis: true });
      x += c.width;
    }
    y += 16;
    doc.moveTo(x0, y).lineTo(x0 + cols.reduce((s, c) => s + c.width, 0), y).strokeColor(PDF.rule).lineWidth(0.5).stroke();
    y += 2;
  }
  doc.y = y + 8;
}

export function footer(doc: PDFKit.PDFDocument, note = "Generated by Pujo Parbon Seller OS · Built by GOBT") {
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    const h = doc.page.height;
    doc.fillColor(PDF.muted).font("Helvetica").fontSize(7.5).text(`${note}   ·   Page ${i + 1} of ${range.count}`, 40, h - 30, { width: doc.page.width - 80, align: "center", lineBreak: false });
  }
}
