import { formatINR } from "@pp/shared";
import { footer, letterhead, newDoc, PDF, table } from "../../lib/pdf";
import { rupeesInWords } from "../../lib/words";
import type { getInvoice } from "./service";

export async function invoicePdf(inv: Awaited<ReturnType<typeof getInvoice>>) {
  const { doc, done } = newDoc();
  letterhead(doc, inv.seller, inv.status === "CANCELLED" ? "Tax Invoice (Cancelled)" : "Tax Invoice", `${inv.number} · ${inv.date}`);

  doc.fillColor(PDF.muted).font("Helvetica").fontSize(8).text("BILL TO", 40, 108);
  doc.fillColor(PDF.ink).font("Helvetica-Bold").fontSize(11).text(inv.customerName, 40, 120);
  doc.font("Helvetica").fontSize(9).fillColor(PDF.muted);
  if (inv.customerGstin) doc.text(`GSTIN ${inv.customerGstin}`, 40, 136);
  doc.text(`Place of supply: ${inv.placeOfSupply}`, 330, 120, { width: 225, align: "right" });
  doc.text(`Channel: ${inv.channelName ?? "Offline"}`, 330, 134, { width: 225, align: "right" });

  const inter = inv.igstPaise > 0;
  table(
    doc,
    [
      { key: "n", label: "#", width: 22 },
      { key: "d", label: "Item", width: 170 },
      { key: "h", label: "HSN", width: 50 },
      { key: "q", label: "Qty", width: 35, align: "right" },
      { key: "r", label: "Rate", width: 65, align: "right" },
      { key: "t", label: "Taxable", width: 70, align: "right" },
      { key: "g", label: "GST", width: 38, align: "right" },
      { key: "x", label: "Tax", width: 65, align: "right" },
    ],
    inv.items.map((i, n) => ({
      n: n + 1, d: i.description, h: i.hsn, q: i.qty, r: formatINR(i.ratePaise), t: formatINR(i.taxablePaise), g: `${i.gstRate}%`, x: formatINR(i.taxPaise),
    })),
    165,
  );

  const lines: [string, number][] = [["Taxable value", inv.subtotalPaise]];
  if (inter) lines.push(["IGST", inv.igstPaise]);
  else lines.push(["CGST", inv.cgstPaise], ["SGST", inv.sgstPaise]);
  let y = doc.y + 4;
  for (const [k, v] of lines) {
    doc.fillColor(PDF.muted).font("Helvetica").fontSize(9.5).text(k, 330, y);
    doc.fillColor(PDF.ink).text(formatINR(v), 430, y, { width: 125, align: "right" });
    y += 16;
  }
  doc.rect(320, y + 2, 235, 30).fill(PDF.tint);
  doc.fillColor(PDF.red).font("Helvetica-Bold").fontSize(12).text("Total", 330, y + 12);
  doc.text(formatINR(inv.totalPaise), 430, y + 12, { width: 115, align: "right" });
  doc.fillColor(PDF.ink).font("Helvetica-Oblique").fontSize(8.5).text(rupeesInWords(inv.totalPaise), 40, y + 44, { width: 515 });
  doc.fillColor(PDF.muted).font("Helvetica").fontSize(8).text("For " + inv.seller.name, 400, y + 90, { width: 155, align: "right" });
  doc.text("Authorised signatory", 400, y + 120, { width: 155, align: "right" });
  footer(doc, "Thank you for shopping with Pujo Parbon · Generated by Seller OS");
  doc.end();
  return done;
}
